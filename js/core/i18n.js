let lang = 'ru';

export const setLang = (next) => {
  lang = dict[next] ? next : 'ru';
  document.documentElement.lang = lang;
};
export const getLang = () => lang;

export function t(key, vars) {
  const table = dict[lang] ?? dict.ru;
  let value = table[key] ?? dict.ru[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) value = value.replace(`{${k}}`, v);
  return value;
}

/** Translate every [data-i18n] node inside a root element. */
export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-ph]').forEach((el) => {
    el.placeholder = t(el.dataset.i18nPh);
  });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
  });
}
